<?php

namespace App\Filament\Resources\TreeQrCodes\Schemas;

use Filament\Infolists\Components\ImageEntry;
use Filament\Infolists\Components\TextEntry;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;

class TreeQrCodeInfolist
{
    public static function configure(Schema $schema): Schema
    {
        return $schema->components([
            Section::make('QR code')
                ->columns(3)
                ->schema([
                    ImageEntry::make('storage_path')->label('Preview')->disk('local')->height(280)->columnSpanFull(),
                    TextEntry::make('tree.tree_code')->label('Tree ID')->badge()->copyable(),
                    TextEntry::make('tree.species.common_name')->label('Tree'),
                    TextEntry::make('status')->badge(),
                    TextEntry::make('public_url')->label('Public profile URL')->copyable()->url(fn ($record): string => $record->public_url)->openUrlInNewTab()->columnSpanFull(),
                    TextEntry::make('version')->badge(),
                    TextEntry::make('print_count')->label('Downloads / prints'),
                    TextEntry::make('generator.name')->label('Generated by')->placeholder('System'),
                    TextEntry::make('generated_at')->label('Generated at')->dateTime(),
                    TextEntry::make('last_printed_at')->label('Last downloaded')->dateTime()->placeholder('Never'),
                ]),
        ]);
    }
}
