<?php

namespace App\Filament\Resources\TreeQrCodes\Tables;

use App\Filament\Resources\TreeQrCodes\Actions\TreeQrCodeActions;
use Filament\Actions\ViewAction;
use Filament\Tables\Columns\TextColumn;
use Filament\Tables\Filters\SelectFilter;
use Filament\Tables\Table;

class TreeQrCodesTable
{
    public static function configure(Table $table): Table
    {
        return $table
            ->defaultSort('generated_at', 'desc')
            ->modifyQueryUsing(fn ($query) => $query->with(['tree.species', 'generator']))
            ->columns([
                TextColumn::make('tree.tree_code')->label('Tree ID')->searchable()->sortable()->copyable()->weight('semibold'),
                TextColumn::make('tree.species.common_name')->label('Tree')->searchable()->sortable(),
                TextColumn::make('status')->badge()->color(fn (string $state): string => $state === 'active' ? 'success' : 'gray')->sortable(),
                TextColumn::make('version')->badge()->sortable(),
                TextColumn::make('print_count')->label('Downloads')->sortable()->alignCenter(),
                TextColumn::make('generator.name')->label('Generated by')->placeholder('System')->toggleable(),
                TextColumn::make('generated_at')->label('Generated')->since()->dateTimeTooltip()->sortable(),
                TextColumn::make('last_printed_at')->label('Last downloaded')->since()->dateTimeTooltip()->placeholder('Never')->sortable()->toggleable(),
            ])
            ->filters([
                SelectFilter::make('status')->options(['active' => 'Active', 'inactive' => 'Inactive'])->native(false),
            ])
            ->recordActions([
                TreeQrCodeActions::regenerate(),
                TreeQrCodeActions::download(),
                TreeQrCodeActions::deactivate(),
                TreeQrCodeActions::activate(),
                ViewAction::make(),
            ]);
    }
}
